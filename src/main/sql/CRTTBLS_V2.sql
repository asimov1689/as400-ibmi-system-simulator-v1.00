-- ── Drop existing (safe re-run, dependents first) ─────────────
DROP VIEW  IF EXISTS CODELIVER1.ELIGIBLE_TRADES;
DROP TABLE IF EXISTS CODELIVER1.POSITION;
DROP TABLE IF EXISTS CODELIVER1.INSTRUMENT;
DROP TABLE IF EXISTS CODELIVER1.MARKET_RULE;
DROP TABLE IF EXISTS CODELIVER1.CUSTODIAN;

-- ── CUSTODIAN ────────────────────────────────────────────────
CREATE TABLE CODELIVER1.CUSTODIAN (
    CUST_ID     CHAR(6)   NOT NULL,
    CUST_NAME   CHAR(40)  NOT NULL,
    MARKET_CD   CHAR(4)   NOT NULL,
    COUNTRY_CD  CHAR(2)   NOT NULL,
    STATUS      CHAR(1)   NOT NULL DEFAULT 'A'
);
ALTER TABLE CODELIVER1.CUSTODIAN ADD PRIMARY KEY (CUST_ID);

-- ── MARKET_RULE ──────────────────────────────────────────────
CREATE TABLE CODELIVER1.MARKET_RULE (
    MARKET_CD       CHAR(4)  NOT NULL,
    INSTR_TYPE      CHAR(4)  NOT NULL,
    MIN_SETTLE_DAYS DEC(2,0) NOT NULL DEFAULT 2,
    ALLOWED_CCY     CHAR(3)  NOT NULL,
    ELIGIBLE        CHAR(1)  NOT NULL DEFAULT 'Y'
);
ALTER TABLE CODELIVER1.MARKET_RULE ADD PRIMARY KEY (MARKET_CD, INSTR_TYPE);

-- ── INSTRUMENT ───────────────────────────────────────────────
CREATE TABLE CODELIVER1.INSTRUMENT (
    ISIN        CHAR(12) NOT NULL,
    INSTR_NAME  CHAR(40) NOT NULL,
    INSTR_TYPE  CHAR(4)  NOT NULL,
    MARKET_CD   CHAR(4)  NOT NULL,
    CCY         CHAR(3)  NOT NULL,
    CUST_ID     CHAR(6)  NOT NULL
);
ALTER TABLE CODELIVER1.INSTRUMENT ADD PRIMARY KEY (ISIN);
ALTER TABLE CODELIVER1.INSTRUMENT
    ADD FOREIGN KEY (CUST_ID) REFERENCES CODELIVER1.CUSTODIAN(CUST_ID);

